def main():
    out_bin_path = MODEL_DIR / 'relation_ontology.bin'
    entries = []
    for lang, categories in OFFICIAL_ONTOLOGY.items():
        for cat, phrases in categories.items():
            for phrase in phrases:
                entries.append((lang, cat, phrase))
    magic = b'CTRDONTO'
    version = 1
    num_entries = len(entries)
    dim = 384
    with open(out_bin_path, 'wb') as f:
        f.write(magic)
        f.write(struct.pack('<III', version, num_entries, dim))
        for lang, cat, phrase in entries:
            lang_bytes = lang.encode('utf-8').ljust(4, b'\0')[:4]
            cat_bytes = cat.encode('utf-8').ljust(12, b'\0')[:12]
            text_bytes = phrase.encode('utf-8')
            text_len = len(text_bytes)
            f.write(lang_bytes)
            f.write(cat_bytes)
            f.write(struct.pack('<H', text_len))
            f.write(text_bytes)
    print(f'Generated {num_entries} official ontology entries to {out_bin_path}')

if __name__ == '__main__':
    main()
